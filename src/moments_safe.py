BANNED_PAT = re.compile('|'.join(BLACKLIST), re.I)

# 隐私与凭证：朋友圈和评论都是公开内容，命中即否决。
# 这条判据放在这里（而不是 output_safe）是为了让"私聊输出"和"朋友圈/评论"共用同一套，
# 避免出现"私聊拦得住手机号、评论拦不住"这种不一致（2026-10-17 离线核互动管道时发现）。
PRIVACY_PAT = re.compile(
    r'sk-[A-Za-z0-9_-]{8,}|BEGIN[ ]+(?:RSA[ ]+)?PRIVATE[ ]+KEY|(?<![0-9])1[3-9][0-9]{9}(?![0-9])',
    re.I)

# 允许的朋友圈选题方向（白名单，生成只能在这些里）
TOPIC_WHITELIST = [
    'travel', 'food', 'photo', 'game', 'agent_life', 'daily', 'season',
]


def _squash(text):
    """规避检测归一化：只保留字母和数字（中文在 Python 里算字母）。

    早期版本只剥空白和少数标点，「政🔥治」「政＿治」这类插入 emoji/全角符号
    的变形能绕过黑名单；现在一律剥掉非字母数字字符，NFKC 先折全角。
    """
    import unicodedata
    return ''.join(ch for ch in unicodedata.normalize('NFKC', str(text or '')) if ch.isalnum())
def is_safe(text):
    """文本是否可发。返回 (是否安全, 命中的黑名单词)。
    查两遍：原文 + 归一化后（防插入空格/标点/零宽字符规避）。"""
    raw = str(text or '')
    hit = BANNED_PAT.findall(raw)
    if hit:
        return (False, hit)
    squashed = _squash(raw)
    if squashed != raw:
        hit2 = BANNED_PAT.findall(squashed)
        return (len(hit2) == 0, hit2)
    return (True, [])


def topic_allowed(topic):
    return topic in TOPIC_WHITELIST


def sanitize_for_moment(text, max_chars=300):
    """发布前最后一道闸：超长否决 + 黑名单命中整体否决。"""
    text = str(text or '').strip()
    if not text:
        raise ValueError('内容为空')
    if len(text) > max_chars:
        raise ValueError('超过朋友圈长度上限')
    ok, hits = is_safe(text)
    if not ok:
        raise ValueError('命中安全黑名单: %s' % ','.join(sorted(set(hits))[:3]))
    if PRIVACY_PAT.search(text):
        # 不回显命中的内容，只说不通过（日志里也不留敏感串）
        raise ValueError('内容疑似含凭证或隐私信息（手机号/密钥）')
    return text
